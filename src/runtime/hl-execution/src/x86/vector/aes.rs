#[cfg(test)]
mod test {
    use super::*;

    fn vector(bytes: [u8; 16]) -> u128 {
        u128::from_le_bytes(bytes)
    }

    #[test]
    fn fips_encrypt_round() {
        let state = vector([
            0x00, 0x10, 0x20, 0x30, 0x40, 0x50, 0x60, 0x70, 0x80, 0x90, 0xa0, 0xb0, 0xc0, 0xd0, 0xe0, 0xf0,
        ]);
        let key = vector([
            0xd6, 0xaa, 0x74, 0xfd, 0xd2, 0xaf, 0x72, 0xfa, 0xda, 0xa6, 0x78, 0xf1, 0xd6, 0xab, 0x76, 0xfe,
        ]);
        let expected = vector([
            0x89, 0xd8, 0x10, 0xe8, 0x85, 0x5a, 0xce, 0x68, 0x2d, 0x18, 0x43, 0xd8, 0xcb, 0x12, 0x8f, 0xe4,
        ]);
        assert_eq!(Aes::execute(state, key, X86AesOperation::Encrypt), expected);
    }

    #[test]
    fn key_assist_uses_both_odd_words() {
        let source = vector([
            0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        ]);
        let expected = vector([
            0xf2, 0x6b, 0x6f, 0xc5, 0x6a, 0x6f, 0xc5, 0xf2, 0xfe, 0xd7, 0xab, 0x76, 0xd6, 0xab, 0x76, 0xfe,
        ]);
        assert_eq!(Aes::execute(0, source, X86AesOperation::KeyAssist(1)), expected);
    }
}
