use crate::x86::X86AesOperation;
use crate::{DecodedInstruction, ScalarInstruction, ScalarIrError, VectorSource};

pub(crate) struct Aes;

impl Aes {
    pub(crate) fn decode(decoded: &DecodedInstruction, map: u8) -> Result<ScalarInstruction, ScalarIrError> {
        if !decoded.prefixes.operand_16 || decoded.prefixes.rep || decoded.prefixes.repne {
            return Err(ScalarIrError::Invalid);
        }
        let operation = match (map, decoded.opcode) {
            (2, 0xdc) => X86AesOperation::Encrypt,
            (2, 0xdd) => X86AesOperation::EncryptLast,
            (2, 0xde) => X86AesOperation::Decrypt,
            (2, 0xdf) => X86AesOperation::DecryptLast,
            (2, 0xdb) => X86AesOperation::InverseMix,
            (3, 0xdf) => X86AesOperation::KeyAssist(decoded.immediate.ok_or(ScalarIrError::Invalid)?.0 as u8),
            _ => return Err(ScalarIrError::Unsupported),
        };
        let source = if decoded.raw_mod == Some(3) {
            VectorSource::Register(decoded.register_operand.ok_or(ScalarIrError::Invalid)?)
        } else {
            VectorSource::Memory(decoded.address.ok_or(ScalarIrError::Invalid)?)
        };
        Ok(ScalarInstruction::Aes {
            operation,
            destination: decoded.register.ok_or(ScalarIrError::Invalid)?,
            source,
        })
    }

    pub(crate) fn execute(state: u128, source: u128, operation: X86AesOperation) -> u128 {
        match operation {
            X86AesOperation::Encrypt => Self::round(state, source, false, false),
            X86AesOperation::EncryptLast => Self::round(state, source, false, true),
            X86AesOperation::Decrypt => Self::round(state, source, true, false),
            X86AesOperation::DecryptLast => Self::round(state, source, true, true),
            X86AesOperation::InverseMix => Self::mix(source, true),
            X86AesOperation::KeyAssist(rcon) => Self::key_assist(source, rcon),
        }
    }

    fn round(state: u128, key: u128, inverse: bool, last: bool) -> u128 {
        let mut bytes = state.to_le_bytes();
        bytes = Self::shift(bytes, inverse);
        for byte in &mut bytes {
            *byte = if inverse {
                INV_SBOX[usize::from(*byte)]
            } else {
                SBOX[usize::from(*byte)]
            };
        }
        let value = u128::from_le_bytes(bytes);
        let value = if last { value } else { Self::mix(value, inverse) };
        value ^ key
    }

    fn shift(input: [u8; 16], inverse: bool) -> [u8; 16] {
        let mut output = [0; 16];
        for column in 0..4 {
            for row in 0..4 {
                let source = if inverse {
                    (column + 4 - row) & 3
                } else {
                    (column + row) & 3
                };
                output[column * 4 + row] = input[source * 4 + row];
            }
        }
        output
    }

    fn mix(value: u128, inverse: bool) -> u128 {
        let mut bytes = value.to_le_bytes();
        for column in bytes.chunks_exact_mut(4) {
            let input = [column[0], column[1], column[2], column[3]];
            let coefficients = if inverse { [14, 11, 13, 9] } else { [2, 3, 1, 1] };
            for row in 0..4 {
                column[row] = (0..4)
                    .map(|index| Self::multiply(input[index], coefficients[(index + 4 - row) & 3]))
                    .fold(0, |left, right| left ^ right);
            }
        }
        u128::from_le_bytes(bytes)
    }

    fn multiply(mut value: u8, mut coefficient: u8) -> u8 {
        let mut result = 0;
        while coefficient != 0 {
            result ^= value & 0_u8.wrapping_sub(coefficient & 1);
            value = value << 1 ^ (0x1b & 0_u8.wrapping_sub(value >> 7));
            coefficient >>= 1;
        }
        result
    }

    fn key_assist(source: u128, rcon: u8) -> u128 {
        let bytes = source.to_le_bytes();
        let mut output = [0; 16];
        for (input, destination) in [(4, 0), (12, 8)] {
            for index in 0..4 {
                output[destination + index] = SBOX[usize::from(bytes[input + index])];
                output[destination + 4 + index] = SBOX[usize::from(bytes[input + (index + 1) % 4])];
            }
            output[destination + 4] ^= rcon;
        }
        u128::from_le_bytes(output)
    }
}

