use std::fmt::Write as _;

use crate::binding;
use crate::implementation::Implementations;
use crate::manifest::Manifest;

pub struct Artifact<'a> {
    manifest: &'a Manifest,
    implementations: &'a Implementations,
}

impl<'a> Artifact<'a> {
    pub fn new(manifest: &'a Manifest, implementations: &'a Implementations) -> Self {
        Self {
            manifest,
            implementations,
        }
    }

    pub fn write(&self) {
        self.generate();
    }

    fn generate(&self) {
        let manifest = self.manifest;
        let mut output = String::new();
        output.push_str(
            "// @generated by build.rs from registry/vk_commands.manifest — DO NOT EDIT.\n\n",
        );

        let mut commands = 0usize;
        let mut stubs = 0usize;
        let mut dispatch = String::new();
        let mut names = String::new();

        for (line_number, line) in manifest.text().lines().enumerate() {
            let line = line.trim_end();
            if line.is_empty() || line.starts_with('#') || line.starts_with("T\t") {
                continue;
            }
            let mut fields = line.split('\t');
            let record = fields.next().unwrap_or("");
            if record != "C" {
                panic!(
                    "manifest line {}: unknown record {record:?}",
                    line_number + 1
                );
            }
            let name = fields.next().unwrap_or("");
            let return_type = fields.next().unwrap_or("void");
            let parameters = fields.next().unwrap_or("");
            if name.is_empty() {
                panic!("manifest line {}: empty name: {line:?}", line_number + 1);
            }

            commands += 1;
            writeln!(
                dispatch,
                "        \"{name}\" => Some({name} as *const () as usize),"
            )
            .unwrap();
            writeln!(names, "    \"{name}\",").unwrap();
            if self.implementations.contains(name) {
                continue;
            }
            stubs += 1;
            binding::emit_stub(&mut output, name, return_type, parameters, manifest.kinds());
        }

        constants(&mut output, commands, stubs, self.implementations.len());
        resolver(&mut output, &dispatch, &names);
        std::fs::write(Manifest::output(), output).unwrap();
    }
}

fn constants(output: &mut String, commands: usize, stubs: usize, implemented: usize) {
    writeln!(
        output,
        "\n/// Total Vulkan `vk*` entry points in the manifest (the exported command surface)."
    )
    .unwrap();
    writeln!(output, "pub const VK_ENTRYPOINTS: usize = {commands};").unwrap();
    writeln!(
        output,
        "/// Entry points emitted as default stubs (not yet hand-implemented)."
    )
    .unwrap();
    writeln!(output, "pub const GENERATED_STUBS: usize = {stubs};").unwrap();
    writeln!(
        output,
        "/// Entry points with real hand-written bodies in `src/`."
    )
    .unwrap();
    writeln!(
        output,
        "pub const IMPLEMENTED_ENTRYPOINTS: usize = {};",
        implemented
    )
    .unwrap();
}

fn resolver(output: &mut String, dispatch: &str, names: &str) {
    writeln!(
        output,
        "\n/// Resolve any exported `vk*` entry point by name to its address. Consulted by the"
    )
    .unwrap();
    writeln!(
        output,
        "/// loader-facing proc-addr resolvers in `crate::icd`. Runtime cast (not a const table)."
    )
    .unwrap();
    writeln!(output, "pub fn dispatch_addr(name: &str) -> Option<usize> {{\n    match name {{\n{dispatch}        _ => None,\n    }}\n}}").unwrap();
    writeln!(
        output,
        "\n/// Every exported `vk*` entry-point name (the completeness census list)."
    )
    .unwrap();
    writeln!(output, "pub static DISPATCH_NAMES: &[&str] = &[\n{names}];").unwrap();
}
