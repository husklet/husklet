#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dimensions() {
        assert_eq!(GLYPH_W, 8);
        assert_eq!(GLYPH_H, 8);
    }

    #[test]
    fn space_is_blank() {
        assert_eq!(EMBEDDED.lookup(' '), [0u8; GLYPH_H]);
        assert!(EMBEDDED.contains(' '));
    }

    #[test]
    fn all_printable_ascii_have_glyphs() {
        for c in 0x20u8..=0x7e {
            let ch = c as char;
            assert!(EMBEDDED.contains(ch), "missing glyph for {ch:?} (0x{c:02x})");
        }
    }

    #[test]
    fn unknown_chars_use_box_fallback() {
        for ch in ['\u{0}', '\u{1b}', 'あ', '€'] {
            assert!(!EMBEDDED.contains(ch), "{ch:?} should not have a dedicated glyph");
            assert_eq!(EMBEDDED.lookup(ch), FALLBACK, "{ch:?} should map to the box fallback");
        }
        // Sanity: the fallback really is a hollow box (solid top/bottom, hollow middle).
        assert_eq!(FALLBACK[0], 0xff);
        assert_eq!(FALLBACK[GLYPH_H - 1], 0xff);
        for row in &FALLBACK[1..GLYPH_H - 1] {
            assert_eq!(*row, 0x81, "middle rows carry only left+right edge bits");
        }
    }

    #[test]
    fn sample_letters_nonzero_and_distinct() {
        let a = EMBEDDED.lookup('A');
        let o = EMBEDDED.lookup('o');
        let eight = EMBEDDED.lookup('8');
        for (name, g) in [("A", &a), ("o", &o), ("8", &eight)] {
            assert!(g.iter().any(|&r| r != 0), "{name} glyph should be non-empty");
        }
        assert_ne!(a, o);
        assert_ne!(a, eight);
        assert_ne!(o, eight);
    }

    #[test]
    fn glyph_matches_msb_orientation() {
        // '1' top row in font8x8 is 0x0C (LSB-first cols 2,3) → MSB-first 0x30 (cols 2,3 from left).
        assert_eq!(EMBEDDED.lookup('1')[0], 0x30);
        // '_' is a solid underline on the bottom row only.
        assert_eq!(EMBEDDED.lookup('_'), [0, 0, 0, 0, 0, 0, 0, 0xff]);
    }

    #[test]
    fn no_set_bits_outside_glyph_width() {
        // With GLYPH_W == 8 this mask is 0xFF, but keep the check general so a narrower cell would
        // catch stray bits in the unused right columns.
        let mask: u8 = if GLYPH_W >= 8 {
            0xff
        } else {
            !((1u16 << (8 - GLYPH_W)) - 1) as u8
        };
        for c in 0x20u8..=0x7e {
            for (row, &bits) in EMBEDDED.lookup(c as char).iter().enumerate() {
                assert_eq!(
                    bits & !mask,
                    0,
                    "char {:?} row {row} has bits outside the left {GLYPH_W} columns",
                    c as char
                );
            }
        }
    }
}
