/* Scalar integer pair-memory coverage for the AArch64-on-x86 DBT. */
__asm__(".global _start\n"
        ".type _start,%function\n"
        ".data\n"
        ".balign 32\n"
        "words:\n"
        ".quad 0x1111222233334444,0x5555666677778888\n"
        ".word 0xffffffff,0x80000000\n"
        ".space 96\n"
        ".text\n"
        "_start:\n"
        "adrp x1,words\n"
        "add x1,x1,:lo12:words\n"
        "mov x20,sp\n"

        /* Signed-offset STP/LDP, including XZR sources/destinations. */
        "ldr x2,[x1]\n"
        "ldr x3,[x1,#8]\n"
        "stp x2,x3,[x1,#32]\n"
        "ldp x4,x5,[x1,#32]\n"
        "cmp x4,x2\n"
        "b.ne 99f\n"
        "cmp x5,x3\n"
        "b.ne 99f\n"
        "stp xzr,xzr,[x1,#48]\n"
        "ldp x6,x7,[x1,#48]\n"
        "orr x6,x6,x7\n"
        "cbnz x6,99f\n"
        "ldp xzr,x22,[x1,#32]\n"
        "cmp x22,x3\n"
        "b.ne 99f\n"

        /* Non-temporal 32-bit pair and zero-extension. */
        "movz w8,#0xabcd\n"
        "movz w9,#0x7654\n"
        "stnp w8,w9,[x1,#64]\n"
        "ldnp w10,w11,[x1,#64]\n"
        "cmp w10,w8\n"
        "b.ne 99f\n"
        "cmp w11,w9\n"
        "b.ne 99f\n"

        /* Pre/post-index update the base after both transfers. */
        "add x12,x1,#80\n"
        "stp x2,x3,[x12,#-16]!\n"
        "add x13,x1,#64\n"
        "cmp x12,x13\n"
        "b.ne 99f\n"
        "ldp x14,x15,[x12],#16\n"
        "add x13,x1,#80\n"
        "cmp x12,x13\n"
        "b.ne 99f\n"
        "cmp x14,x2\n"
        "b.ne 99f\n"
        "cmp x15,x3\n"
        "b.ne 99f\n"

        /* LDPSW sign-extends both words, and SP is a real pair base. */
        "ldpsw x16,x17,[x1,#16]\n"
        "movn x18,#0\n"
        "cmp x16,x18\n"
        "b.ne 99f\n"
        "movz x18,#0x8000,lsl #16\n"
        "movk x18,#0xffff,lsl #32\n"
        "movk x18,#0xffff,lsl #48\n"
        "cmp x17,x18\n"
        "b.ne 99f\n"
        "add sp,x1,#32\n"
        "ldp x4,x5,[sp]\n"
        "cmp x4,x2\n"
        "b.ne 98f\n"
        "cmp x5,x3\n"
        "b.ne 98f\n"
        "mov sp,x20\n"

        /* Base overlap without writeback reads the address before writes. */
        "mov x19,x1\n"
        "ldp x19,x21,[x19]\n"
        "cmp x19,x2\n"
        "b.ne 99f\n"
        "cmp x21,x3\n"
        "b.ne 99f\n"

        "movz x0,#42\n"
        "b 1f\n"
        "98:\n"
        "mov sp,x20\n"
        "99:\n"
        "movz x0,#1\n"
        "1:\n"
        "movz x8,#93\n"
        "svc #0\n"
        ".size _start,.-_start\n");
