/* Scalar single-register memory coverage for the AArch64-on-x86 DBT. Every
 * transfer is checked before the next form, so an addressing, extension,
 * writeback, SP or ZR mistake cannot be hidden by the final exit status. */
__asm__(".global _start\n"
        ".type _start,%function\n"
        ".data\n"
        ".balign 16\n"
        "bytes:\n"
        ".byte 0x80,0x7f,0x34,0x12,0x78,0x56,0x34,0x12\n"
        ".quad 0x1122334455667788\n"
        ".space 32\n"
        ".text\n"
        "_start:\n"
        "adrp x1,bytes\n"
        "add x1,x1,:lo12:bytes\n"
        "mov x20,sp\n"

        /* Unsigned-offset and zero/sign extension. */
        "ldrb w2,[x1]\n"
        "cmp w2,#0x80\n"
        "b.ne 99f\n"
        "ldrsb x3,[x1]\n"
        "movn x14,#0x7f\n"
        "cmp x3,x14\n"
        "b.ne 99f\n"
        "ldrh w4,[x1,#2]\n"
        "movz w5,#0x1234\n"
        "cmp w4,w5\n"
        "b.ne 99f\n"
        "ldr w4,[x1,#4]\n"
        "movz w5,#0x5678\n"
        "movk w5,#0x1234,lsl #16\n"
        "cmp w4,w5\n"
        "b.ne 99f\n"
        "ldr x6,[x1,#8]\n"
        "prfm pldl1keep,[x1,#8]\n"

        /* Dominant post/pre-index byte forms and their writeback. */
        "mov x7,x1\n"
        "ldrb w8,[x7],#1\n"
        "cmp w8,#0x80\n"
        "b.ne 99f\n"
        "add x9,x1,#1\n"
        "cmp x7,x9\n"
        "b.ne 99f\n"
        "ldrb w8,[x7,#1]!\n"
        "cmp w8,#0x34\n"
        "b.ne 99f\n"
        "add x9,x1,#2\n"
        "cmp x7,x9\n"
        "b.ne 99f\n"

        /* Unscaled, register-offset, and a deliberately unaligned load. */
        "ldursh w11,[x1,#2]\n"
        "movz w17,#0x1234\n"
        "cmp w11,w17\n"
        "b.ne 99f\n"
        "movz w10,#1\n"
        "ldrh w11,[x1,w10,uxtw #1]\n"
        "cmp w11,w17\n"
        "b.ne 99f\n"
        "ldr x12,[x1,#1]\n"
        "movz x13,#0x347f\n"
        "movk x13,#0x7812,lsl #16\n"
        "movk x13,#0x3456,lsl #32\n"
        "movk x13,#0x8812,lsl #48\n"
        "cmp x12,x13\n"
        "b.ne 99f\n"

        /* Store widths, ZR discard/zero source, and SP as the base. */
        "strb w2,[x1,#16]\n"
        "strh w5,[x1,#18]\n"
        "str w4,[x1,#20]\n"
        "str x6,[x1,#24]\n"
        "ldr xzr,[x1,#24]\n"
        "strb wzr,[x1,#17]\n"
        "ldrb w15,[x1,#17]\n"
        "cbnz w15,99f\n"
        "add sp,x1,#16\n"
        "ldr x16,[sp,#8]\n"
        "cmp x16,x6\n"
        "b.ne 99f\n"
        "mov sp,x20\n"

        "movz x0,#42\n"
        "b 1f\n"
        "99:\n"
        "mov sp,x20\n"
        "movz x0,#1\n"
        "1:\n"
        "movz x8,#93\n"
        "svc #0\n"
        ".size _start,.-_start\n");
